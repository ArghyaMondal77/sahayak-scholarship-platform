/**
 * Look up a UI string.
 * Falls back to English, then to the key itself.
 * Unknown languages default to 'en'.
 */
export function t(lang, key) {
  const safeLang = Object.prototype.hasOwnProperty.call(translations, lang) ? lang : 'en';
  return translations[safeLang]?.[key] ?? translations.en[key] ?? key;
}
